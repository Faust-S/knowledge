#!/usr/bin/env python3
"""Exploratory TASK-EXP-01 source-cue comparison after human adjudication.

This is NOT Task-level precision/recall/F1, E5 evaluation, a Task Engine, or
automatic approval. It compares independently pinned full-source literal hits and frozen
U1/title-regex lexical cues with manually reported source-level decisions.
Real independent adjudication must happen elsewhere before using this tool.
No source text, region labels, reviewer identities or per-source outcomes
appear in the output.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import sys

import exact_search_baseline as literal
import method_snapshot as frozen
import review_effort as effort
import source_first_baseline as baseline

SCHEMA = "IWXA_TASK_EXP_01_EXPLORATORY_SOURCE_CUE_COMPARISON/0.1"
INPUT_SCHEMA = "IWXA_TASK_EXP_01_MANUAL_SOURCE_ADJUDICATION/0.1"
EXPECTED_METHOD_SHA = effort.EXPECTED_METHOD_SHA
ALLOWED = frozenset(("TASK_PRESENT", "NO_TASK", "UNRESOLVED"))
METHODS = ("title_regex", "pinned_u1", "either_cue", "literal_exact")
BLANK_RESOLUTION = "PENDING_HUMAN_ADJUDICATION"


class ComparisonHold(ValueError):
    """Only fixed refusal codes; never raw reviewer or issue content."""


def need(ok: bool, code: str) -> None:
    if not ok:
        raise ComparisonHold(code)


def ratio(num: int, den: int) -> float | None:
    return (num / den) if den else None


def confusion(cues: set[str], labels: dict[str, str]) -> dict:
    resolved = {k: v for k, v in labels.items() if v != "UNRESOLVED"}
    tp = sum(k in cues and v == "TASK_PRESENT" for k, v in resolved.items())
    fp = sum(k in cues and v == "NO_TASK" for k, v in resolved.items())
    fn = sum(k not in cues and v == "TASK_PRESENT" for k, v in resolved.items())
    tn = sum(k not in cues and v == "NO_TASK" for k, v in resolved.items())
    precision = ratio(tp, tp + fp)
    recall = ratio(tp, tp + fn)
    # F1 uses its own denominator. A method that finds no cues while a
    # confirmed positive exists has F1=0 (FN>0), even though precision is
    # undefined. Likewise false positives without any gold positive give
    # F1=0 despite undefined recall. Only 0/0 is unmeasurable.
    f1 = ratio(2 * tp, 2 * tp + fp + fn)
    return {
        "tp": tp, "fp": fp, "fn": fn, "tn": tn,
        "resolved_denominator": len(resolved),
        "cue_positive_denominator": tp + fp,
        "gold_positive_denominator": tp + fn,
        "unresolved_excluded": len(labels) - len(resolved),
        "precision": precision, "recall": recall, "f1": f1,
    }


def analyze(manifest: dict, snapshot: dict, adjudication: dict, *,
            literal_snapshot: dict | None = None) -> dict:
    """Compare only the pinned *source-cue* method, never caller-supplied SHA."""
    need(type(manifest) is dict and
         manifest.get("schema") == "IWXA_TASK_EXP_01_PUBLIC_ISSUE_SOURCE_SLICE/0.1" and
         manifest.get("no_gold") is True and
         type(manifest.get("items")) is list and len(manifest["items"]) == 8,
         "FROZEN_SOURCE_SELECTION_INVALID")
    sources = {r["projection_sha256"]: r for r in manifest["items"]}
    need(len(sources) == 8 and all(type(k) is str and len(k) == 64
                                   for k in sources),
         "FROZEN_SOURCE_IDENTITY_INVALID")
    need(type(snapshot) is dict and snapshot.get("schema") == frozen.SCHEMA and
         snapshot.get("method_output_sha256") == EXPECTED_METHOD_SHA and
         snapshot.get("frozen_manifest_git_blob") == frozen.MANIFEST_GIT_BLOB and
         snapshot.get("owner_u1_git_blob") == frozen.OWNER_U1_GIT_BLOB and
         snapshot.get("human_gold") is False and
         snapshot.get("task_candidates_created") == 0 and
         type(snapshot.get("source_rows")) is list and
         len(snapshot["source_rows"]) == 8,
         "FROZEN_METHOD_REPLAY_NOT_VERIFIED")
    # This function must receive a snapshot regenerated by replay_method(),
    # not accept an arbitrary uploaded method output as scientific evidence.
    index = {}
    for r in snapshot["source_rows"]:
        need(type(r) is dict and
             set(r) == {"source_ref", "source_sha256", "u1_raw_statements",
                        "title_regex_cue_spans", "u1_review_cue_spans"},
             "METHOD_SOURCE_ROW_INVALID")
        sha = r["source_sha256"]
        need(type(sha) is str and sha in sources and sha not in index and
             r["source_ref"] == sources[sha]["html_url"] and
             type(r["u1_raw_statements"]) is int and
             r["u1_raw_statements"] >= 0,
             "METHOD_SOURCE_IDENTITY_CHANGED")
        size = sources[sha]["projection_bytes"]
        frozen.validate_spans(r["title_regex_cue_spans"], size, "TITLE", with_kind=False)
        frozen.validate_spans(r["u1_review_cue_spans"], size, "U1", with_kind=True)
        index[sha] = r
    need(set(index) == set(sources), "METHOD_SOURCE_SET_INCOMPLETE")
    # Rebuild exactly the payload hashed before review by method_snapshot.
    # Checking only the stored SHA would accept modified cue coordinates
    # disguised under that previously pinned digest. No new method is run.
    payload = {
        "sources": [index[item["projection_sha256"]]
                    for item in manifest["items"]],
        "title_pattern_sha256": baseline.sha(
            baseline.TITLE_PATTERN.encode("utf-8")),
        "owner_u1_blob": frozen.OWNER_U1_GIT_BLOB,
    }
    need(frozen.canonical_sha(payload) == EXPECTED_METHOD_SHA,
         "FROZEN_METHOD_COORDINATES_CHANGED")

    need(type(adjudication) is dict and set(adjudication) == {
        "schema", "human_adjudication_claimed", "methods_hidden_during_review",
        "sources"} and adjudication["schema"] == INPUT_SCHEMA and
        adjudication["human_adjudication_claimed"] is True and
        adjudication["methods_hidden_during_review"] is True and
        type(adjudication["sources"]) is list and len(adjudication["sources"]) == 8,
        "MANUAL_ADJUDICATION_NOT_CONFIRMED")
    labels = {}
    for row in adjudication["sources"]:
        need(type(row) is dict and
             set(row) == {"source_sha256", "resolution"},
             "MANUAL_ADJUDICATION_ROW_INVALID")
        sha, state = row["source_sha256"], row["resolution"]
        need(type(sha) is str and sha in sources and sha not in labels and
             type(state) is str and state in ALLOWED,
             "MANUAL_SOURCE_SELECTION_OR_RESOLUTION_INVALID")
        labels[sha] = state
    need(set(labels) == set(sources), "MANUAL_SOURCE_SET_INCOMPLETE")

    # The literal search has a separate pre-gold SHA commitment. It is not
    # part of the older U1/title method hash and does not change it.
    literal_status = "PINNED_LITERAL_AVAILABLE_NOT_REPLAYED"
    literal_rows = None
    if literal_snapshot is not None:
        need(literal.frozen.canonical_sha(literal.specification()) == literal.SPEC_SHA,
             "FROZEN_LITERAL_SPECIFICATION_CHANGED")
        need(type(literal_snapshot) is dict and
             literal_snapshot.get("schema") == literal.SCHEMA and
             literal_snapshot.get("status") == "PINNED_LITERAL_SEARCH_BEFORE_HUMAN_GOLD" and
             literal_snapshot.get("frozen_manifest_git_blob") == frozen.MANIFEST_GIT_BLOB and
             literal_snapshot.get("method_spec_sha256") == literal.SPEC_SHA and
             literal_snapshot.get("method_output_sha256") == literal.OUTPUT_SHA and
             literal_snapshot.get("sources_verified") == 8 and
             literal_snapshot.get("human_gold") is False and
             literal_snapshot.get("source_text_exported") is False and
             all(literal_snapshot.get(k) is None for k in
                 ("task_precision", "task_recall", "task_f1")),
             "FROZEN_LITERAL_REPLAY_NOT_VERIFIED")
        literal_rows = literal_snapshot.get("source_rows")
        need(type(literal_rows) is list and len(literal_rows) == 8 and
             all(type(row) is dict and
                 set(row) == {"source_sha256", "hit"} and
                 type(row["source_sha256"]) is str and
                 type(row["hit"]) is bool for row in literal_rows) and
             [row["source_sha256"] for row in literal_rows] ==
             [item["projection_sha256"] for item in manifest["items"]],
             "FROZEN_LITERAL_SOURCE_ROWS_INVALID")
        hits = sum(row["hit"] for row in literal_rows)
        need(type(literal_snapshot.get("sources_with_literal_hit")) is int and
             type(literal_snapshot.get("sources_without_literal_hit_still_included")) is int and
             literal_snapshot["sources_with_literal_hit"] == hits and
             literal_snapshot["sources_without_literal_hit_still_included"] == 8 - hits,
             "FROZEN_LITERAL_REPLAY_NOT_VERIFIED")
        need(literal.source_output_sha(literal_rows) == literal.OUTPUT_SHA,
             "FROZEN_LITERAL_SOURCE_HITS_CHANGED")
        literal_status = "PINNED_FULL_SOURCE_LITERAL_HITS_SCORED_NOT_TASK"

    title = {k for k, v in index.items() if v["title_regex_cue_spans"]}
    u1 = {k for k, v in index.items() if v["u1_review_cue_spans"]}
    groups = {"title_regex": title, "pinned_u1": u1, "either_cue": title | u1}
    if literal_rows is not None:
        groups["literal_exact"] = {
            row["source_sha256"] for row in literal_rows if row["hit"]}
    counted = {name: confusion(group, labels) for name, group in groups.items()}
    return {
        "schema": SCHEMA,
        "status": "EXPLORATORY_SOURCE_CUE_ASSOCIATION_SELF_REPORTED_NOT_E5",
        "frozen_method_output_sha256": EXPECTED_METHOD_SHA,
        "frozen_manifest_git_blob": frozen.MANIFEST_GIT_BLOB,
        "sources_selected": 8,
        "resolved_sources": sum(v != "UNRESOLVED" for v in labels.values()),
        "unresolved_sources": sum(v == "UNRESOLVED" for v in labels.values()),
        "source_retrieval": counted,
        "full_source_reading_required": 8,
        "exact_search_baseline": literal_status,
        "literal_exact_spec_sha256": literal.SPEC_SHA if literal_rows is not None else None,
        "literal_exact_output_sha256": literal.OUTPUT_SHA if literal_rows is not None else None,
        "human_independence_independently_verified": False,
        "manual_adjudication_attestation_independently_verified": False,
        "human_gold": False,
        "task_precision": None, "task_recall": None, "task_f1": None,
        "human_active_time_measured": False,
        "economic_comparison_measured": False,
        "source_text_exported": False,
        "individual_source_resolutions_exported": False,
        "reviewer_id_exported": False,
    }


def prepare_manual_resolution(path: Path) -> dict:
    """Prepare eight pinned source IDs, never a human decision or task gold.

    Keep this editable local handoff outside the Git checkout. A third
    independent expert must later supply all resolutions and attestations.
    The unchanged analyzer deliberately rejects this blank file.
    """
    manifest = literal.checked_manifest()
    sources = [item["projection_sha256"] for item in manifest["items"]]
    need(len(sources) == len(set(sources)) == 8 and
         all(type(sha) is str and len(sha) == 64 and
             all(ch in "0123456789abcdef" for ch in sha)
             for sha in sources),
         "FROZEN_SOURCE_IDENTITY_INVALID")
    repo_root = frozen.SELECTION.parents[2].resolve()
    need(not path.resolve().is_relative_to(repo_root),
         "MANUAL_ADJUDICATION_OUTPUT_INSIDE_CHECKOUT")
    need(not path.exists() and not path.is_symlink(),
         "MANUAL_ADJUDICATION_OUTPUT_EXISTS")
    need(path.parent.is_dir(), "MANUAL_ADJUDICATION_OUTPUT_PARENT_UNAVAILABLE")
    template = {
        "schema": INPUT_SCHEMA,
        "human_adjudication_claimed": False,
        "methods_hidden_during_review": False,
        "sources": [
            {"source_sha256": sha, "resolution": BLANK_RESOLUTION}
            for sha in sources
        ],
    }
    try:
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8") as stream:
            json.dump(template, stream, sort_keys=True, ensure_ascii=False,
                      indent=2, allow_nan=False)
            stream.write("\n")
    except (OSError, TypeError, ValueError, UnicodeError):
        raise ComparisonHold("MANUAL_ADJUDICATION_TEMPLATE_WRITE_FAILED") from None
    return {
        "status": "EIGHT_SOURCE_MANUAL_ADJUDICATION_TEMPLATE_NOT_GOLD",
        "sources": 8, "unresolved_human_decisions": 8, "human_gold": False,
    }


def replay_method(input_dir: Path | None = None, *,
                  get_source=None) -> tuple[dict, dict]:
    """Regenerate the existing pre-gold U1/title method, never update it."""
    import paired_pinned_u1 as paired
    need(frozen.git_blob_sha(frozen.SELECTION.read_bytes()) ==
         frozen.MANIFEST_GIT_BLOB, "SOURCE_MANIFEST_BLOB_CHANGED")
    manifest = baseline.read_manifest(frozen.SELECTION)
    snapshot = frozen.freeze(manifest, paired.paired_run(
        manifest, input_dir=input_dir, get_source=get_source))
    need(snapshot["method_output_sha256"] == EXPECTED_METHOD_SHA,
         "PRE_GOLD_METHOD_HASH_CHANGED")
    return manifest, snapshot


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    mode = p.add_mutually_exclusive_group(required=True)
    mode.add_argument("--manual-adjudication", type=Path)
    mode.add_argument("--prepare-manual-resolution", type=Path,
                      help="Write blank eight-source owner-local template outside checkout")
    p.add_argument("--input-dir", type=Path)
    opts = p.parse_args()
    try:
        if opts.prepare_manual_resolution is not None:
            need(opts.input_dir is None, "MANUAL_TEMPLATE_DOES_NOT_USE_SOURCE_TEXT")
            result = prepare_manual_resolution(opts.prepare_manual_resolution)
            print(json.dumps(result, sort_keys=True))
            return 0
        # Never upload or print the adjudication rows or replay coordinates.
        adjudication = effort.read_json(opts.manual_adjudication)
        # Read each immutable original source once for both pinned methods.
        # The U1/title commitment and the newer literal commitment stay
        # separate; neither method sees the independent review labels.
        source_cache = {}
        def source_once(item: dict) -> bytes:
            key = item["projection_sha256"]
            if key not in source_cache:
                source_cache[key] = baseline._projection(item, opts.input_dir)
            return source_cache[key]

        manifest, snapshot = replay_method(opts.input_dir, get_source=source_once)
        exact = literal.replay(manifest, fetch_source=source_once)
        result = analyze(manifest, snapshot, adjudication, literal_snapshot=exact)
        print(json.dumps(result, sort_keys=True, allow_nan=False))
        return 0
    except (ComparisonHold, frozen.SnapshotHold, baseline.BaselineHold,
            literal.ExactHold, effort.EffortHold, OSError, ValueError, TypeError, KeyError):
        print(json.dumps({"status": "HOLD",
                          "code": "SOURCE_CUE_EXPLORATORY_ANALYSIS_INCOMPLETE"},
                         sort_keys=True), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
