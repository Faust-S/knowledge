#!/usr/bin/env python3
"""Exploratory TASK-EXP-01 source-cue comparison after human adjudication.

This is NOT Task-level precision/recall/F1, E5 evaluation, a Task Engine, or
automatic approval. It only compares the frozen U1 and title-regex *presence
of lexical review cues* with manually reported source-level decisions.
Real independent adjudication must happen elsewhere before using this tool.
No source text, region labels, reviewer identities or per-source outcomes
appear in the output.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

import method_snapshot as frozen
import review_effort as effort
import source_first_baseline as baseline

SCHEMA = "IWXA_TASK_EXP_01_EXPLORATORY_SOURCE_CUE_COMPARISON/0.1"
INPUT_SCHEMA = "IWXA_TASK_EXP_01_MANUAL_SOURCE_ADJUDICATION/0.1"
EXPECTED_METHOD_SHA = effort.EXPECTED_METHOD_SHA
ALLOWED = frozenset(("TASK_PRESENT", "NO_TASK", "UNRESOLVED"))
METHODS = ("title_regex", "pinned_u1", "either_cue")


class ComparisonHold(ValueError):
    """Only fixed refusal codes; never raw reviewer or issue content."""


def need(ok: bool, code: str) -> None:
    if not ok:
        raise ComparisonHold(code)


def ratio(num: int, den: int) -> float | None:
    return (num / den) if den else None


def confusion(cues: set[str], labels: dict[str, str]) -> dict:
    resolved = {k: v for k, v in labels.items() if v != "UNRESOLVED"}
    tp = sum(k in cues and v == "TASK_PRESENT" for k, v in resolved.items())
    fp = sum(k in cues and v == "NO_TASK" for k, v in resolved.items())
    fn = sum(k not in cues and v == "TASK_PRESENT" for k, v in resolved.items())
    tn = sum(k not in cues and v == "NO_TASK" for k, v in resolved.items())
    precision = ratio(tp, tp + fp)
    recall = ratio(tp, tp + fn)
    f1 = ratio(2 * tp, 2 * tp + fp + fn) if (
        precision is not None and recall is not None) else None
    return {
        "tp": tp, "fp": fp, "fn": fn, "tn": tn,
        "resolved_denominator": len(resolved),
        "cue_positive_denominator": tp + fp,
        "gold_positive_denominator": tp + fn,
        "unresolved_excluded": len(labels) - len(resolved),
        "precision": precision, "recall": recall, "f1": f1,
    }


def analyze(manifest: dict, snapshot: dict, adjudication: dict, *,
            method_sha: str = EXPECTED_METHOD_SHA) -> dict:
    """Return descriptive *source-retrieval* metrics, not Task accuracy."""
    need(type(manifest) is dict and
         manifest.get("schema") == "IWXA_TASK_EXP_01_PUBLIC_ISSUE_SOURCE_SLICE/0.1" and
         manifest.get("no_gold") is True and
         type(manifest.get("items")) is list and len(manifest["items"]) == 8,
         "FROZEN_SOURCE_SELECTION_INVALID")
    sources = {r["projection_sha256"]: r for r in manifest["items"]}
    need(len(sources) == 8 and all(type(k) is str and len(k) == 64
                                   for k in sources),
         "FROZEN_SOURCE_IDENTITY_INVALID")
    need(type(snapshot) is dict and snapshot.get("schema") == frozen.SCHEMA and
         snapshot.get("method_output_sha256") == method_sha and
         snapshot.get("frozen_manifest_git_blob") == frozen.MANIFEST_GIT_BLOB and
         snapshot.get("owner_u1_git_blob") == frozen.OWNER_U1_GIT_BLOB and
         snapshot.get("human_gold") is False and
         snapshot.get("task_candidates_created") == 0 and
         type(snapshot.get("source_rows")) is list and
         len(snapshot["source_rows"]) == 8,
         "FROZEN_METHOD_REPLAY_NOT_VERIFIED")
    # This function must receive a snapshot regenerated by replay_method(),
    # not accept an arbitrary uploaded method output as scientific evidence.
    index = {}
    for r in snapshot["source_rows"]:
        need(type(r) is dict and
             set(r) == {"source_ref", "source_sha256", "u1_raw_statements",
                        "title_regex_cue_spans", "u1_review_cue_spans"},
             "METHOD_SOURCE_ROW_INVALID")
        sha = r["source_sha256"]
        need(type(sha) is str and sha in sources and sha not in index and
             r["source_ref"] == sources[sha]["html_url"] and
             type(r["u1_raw_statements"]) is int and
             r["u1_raw_statements"] >= 0,
             "METHOD_SOURCE_IDENTITY_CHANGED")
        size = sources[sha]["projection_bytes"]
        frozen.validate_spans(r["title_regex_cue_spans"], size, "TITLE", with_kind=False)
        frozen.validate_spans(r["u1_review_cue_spans"], size, "U1", with_kind=True)
        index[sha] = r
    need(set(index) == set(sources), "METHOD_SOURCE_SET_INCOMPLETE")

    need(type(adjudication) is dict and set(adjudication) == {
        "schema", "human_adjudication_claimed", "methods_hidden_during_review",
        "sources"} and adjudication["schema"] == INPUT_SCHEMA and
        adjudication["human_adjudication_claimed"] is True and
        adjudication["methods_hidden_during_review"] is True and
        type(adjudication["sources"]) is list and len(adjudication["sources"]) == 8,
        "MANUAL_ADJUDICATION_NOT_CONFIRMED")
    labels = {}
    for row in adjudication["sources"]:
        need(type(row) is dict and
             set(row) == {"source_sha256", "resolution"},
             "MANUAL_ADJUDICATION_ROW_INVALID")
        sha, state = row["source_sha256"], row["resolution"]
        need(type(sha) is str and sha in sources and sha not in labels and
             type(state) is str and state in ALLOWED,
             "MANUAL_SOURCE_SELECTION_OR_RESOLUTION_INVALID")
        labels[sha] = state
    need(set(labels) == set(sources), "MANUAL_SOURCE_SET_INCOMPLETE")

    title = {k for k, v in index.items() if v["title_regex_cue_spans"]}
    u1 = {k for k, v in index.items() if v["u1_review_cue_spans"]}
    groups = {"title_regex": title, "pinned_u1": u1, "either_cue": title | u1}
    counted = {name: confusion(group, labels) for name, group in groups.items()}
    return {
        "schema": SCHEMA,
        "status": "EXPLORATORY_SOURCE_CUE_ASSOCIATION_SELF_REPORTED_NOT_E5",
        "frozen_method_output_sha256": method_sha,
        "frozen_manifest_git_blob": frozen.MANIFEST_GIT_BLOB,
        "sources_selected": 8,
        "resolved_sources": sum(v != "UNRESOLVED" for v in labels.values()),
        "unresolved_sources": sum(v == "UNRESOLVED" for v in labels.values()),
        "source_retrieval": counted,
        "full_source_reading_required": 8,
        "exact_search_baseline": "NOT_FROZEN_NOT_SCORED",
        "human_independence_independently_verified": False,
        "manual_adjudication_attestation_independently_verified": False,
        "human_gold": False,
        "task_precision": None, "task_recall": None, "task_f1": None,
        "human_active_time_measured": False,
        "economic_comparison_measured": False,
        "source_text_exported": False,
        "individual_source_resolutions_exported": False,
        "reviewer_id_exported": False,
    }


def replay_method(input_dir: Path | None = None) -> tuple[dict, dict]:
    """Regenerate the existing pre-gold U1/title method, never update it."""
    import paired_pinned_u1 as paired
    need(frozen.git_blob_sha(frozen.SELECTION.read_bytes()) ==
         frozen.MANIFEST_GIT_BLOB, "SOURCE_MANIFEST_BLOB_CHANGED")
    manifest = baseline.read_manifest(frozen.SELECTION)
    snapshot = frozen.freeze(manifest, paired.paired_run(manifest, input_dir=input_dir))
    need(snapshot["method_output_sha256"] == EXPECTED_METHOD_SHA,
         "PRE_GOLD_METHOD_HASH_CHANGED")
    return manifest, snapshot


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--manual-adjudication", required=True, type=Path)
    p.add_argument("--input-dir", type=Path)
    opts = p.parse_args()
    try:
        # Never upload or print the adjudication rows or replay coordinates.
        adjudication = effort.read_json(opts.manual_adjudication)
        manifest, snapshot = replay_method(opts.input_dir)
        result = analyze(manifest, snapshot, adjudication)
        print(json.dumps(result, sort_keys=True, allow_nan=False))
        return 0
    except (ComparisonHold, frozen.SnapshotHold, baseline.BaselineHold,
            effort.EffortHold, OSError, ValueError, TypeError, KeyError):
        print(json.dumps({"status": "HOLD",
                          "code": "SOURCE_CUE_EXPLORATORY_ANALYSIS_INCOMPLETE"},
                         sort_keys=True), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
