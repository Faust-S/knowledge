#!/usr/bin/env node
/** Canonical generated runtime-version materializer/parity checker. */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { isMainModule } from "./is-main-module.mjs";

const ROOT = process.cwd();
export const CONTRACT_VERSION = "1.3.0";
export const MIN_LOADER = 1;

export function readRuntimeVersion(root = ROOT) {
  const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
  if (!/^\d+\.\d+\.\d+(?:[-+].+)?$/.test(pkg.version)) {
    throw new Error(`package.json.version "${pkg.version}" is not semver`);
  }
  return pkg.version;
}

export function expectedRuntimeVersionSource(root = ROOT) {
  const version = readRuntimeVersion(root);
  return (
    `// AUTO-GENERATED by scripts/sync-runtime-version.mjs. Do not edit.\n` +
    `// Sourced from package.json — the single semver authority.\n` +
    `export const RUNTIME_VERSION = ${JSON.stringify(version)};\n` +
    `export const CONTRACT_VERSION = ${JSON.stringify(CONTRACT_VERSION)};\n` +
    `export const MIN_LOADER = ${MIN_LOADER};\n`
  );
}

export function checkRuntimeVersionParity(root = ROOT) {
  const out = join(root, "src", "generated", "runtime-version.ts");
  const expected = expectedRuntimeVersionSource(root);
  const actual = existsSync(out) ? readFileSync(out, "utf8") : "";
  return { ok: actual === expected, out, expected, actual, version: readRuntimeVersion(root) };
}

export function writeRuntimeVersion(root = ROOT) {
  const result = checkRuntimeVersionParity(root);
  if (!existsSync(dirname(result.out))) mkdirSync(dirname(result.out), { recursive: true });
  if (!result.ok) writeFileSync(result.out, result.expected);
  return { ...result, changed: !result.ok };
}

if (isMainModule(import.meta.url)) {
  const mode = process.argv[2] ?? "--write";
  try {
    if (mode === "--check") {
      const r = checkRuntimeVersionParity();
      if (!r.ok) {
        console.error(`[runtime-version] DRIFT: ${r.out}; run npm run sync:version before source freeze.`);
        process.exit(1);
      }
      console.log(`[runtime-version] PARITY PASS runtime=${r.version} contract=${CONTRACT_VERSION} min_loader=${MIN_LOADER}`);
    } else if (mode === "--write") {
      const r = writeRuntimeVersion();
      console.log(`[runtime-version] ${r.changed ? "MATERIALIZED" : "NO-OP"} runtime=${r.version} contract=${CONTRACT_VERSION} min_loader=${MIN_LOADER}`);
    } else {
      console.error("Usage: sync-runtime-version.mjs [--check|--write]");
      process.exit(64);
    }
  } catch (error) {
    console.error(`[runtime-version] ${error instanceof Error ? error.message : String(error)}`);
    process.exit(1);
  }
}
