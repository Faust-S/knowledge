import test from "node:test";
import assert from "node:assert/strict";
import {createHash} from "node:crypto";
import {createTrustedOriginalAgentResultPublication,
  ORIGINAL_AGENT_PUBLICATION,ORIGINAL_AGENT_RESULT_SCHEMA,
  ORIGINAL_AGENT_RESULT_EVENT} from "../src/t3/original-agent-result-publication.mjs";

// Source-only contract fixture. Real installed employee signer, T2 Kernel
// and native signed original Exchange remain independent product owners.
const hex=value=>createHash("sha256").update(value).digest("hex");
const sorted=value=>Array.isArray(value)
  ? "["+value.map(sorted).join(",")+"]"
  : value&&typeof value==="object"
    ? "{"+Object.keys(value).sort().map(k=>JSON.stringify(k)+":"+sorted(value[k])).join(",")+"}"
    : JSON.stringify(value);
function fixture({lostAck=false,acceptanceValid=true,denyExport=false}={}){
  const workspace_id="ws:agent-publish-only",writes=[],readers=new Map();
  const events=[],receipts=new Map(),sends=[];
  const workRef={projectId:"proj:real",workId:"work:203",revision:"3"};
  const binding={schema:ORIGINAL_AGENT_PUBLICATION,recipientId:"iwxa.atlas",
    signedTaskId:"task:corp:1",signedTaskRevisionId:"taskrev:1",
    signedTaskPackageSha256:"a".repeat(64),
    taskId:"TASK-CHAT-0123456789abcdef01234567",resultId:"RES-0001",
    acceptedDigest:"b".repeat(64),workRef,contextDigest:"c".repeat(64)};
  const operationId="agent:t3:atlas:"+hex(Buffer.from(sorted(binding),"utf8"));
  const text="Accepted original Agent result, not generated by Atlas";
  const context={kind:"CORP",context_id:"ctx:employee:1",
    actor_id:"person:employee",principal_id:"org:one",role_id:"worker",
    grant_id:"grant:publish",realm_id:"realm:org",audience:"t3:agent",
    resource:workspace_id,purpose:"workspace.work",
    workspace_id,organization_id:"org:one",scope_revision:1};
  const later=()=>new Date(Date.now()+3600000).toISOString();
  const now=()=>new Date().toISOString();
  const access={
    currentContext:()=>context,
    actionFor:op=>op==="t1.putObject"?"object.write":
      op.startsWith("t2.")?"package.export":"workspace.read",
    operationDigest:({operation,input})=>hex(JSON.stringify({operation,input})),
    authorize:request=>({
      schema:"IWXA_T3_ORGANIZATION_OPERATION_DECISION/1",
      allowed:true,outcome:"PERMITTED",evidenceOnly:true,
      requestDigest:"d".repeat(64),policyDigest:"e".repeat(64),
      operationDigest:"f".repeat(64),evidenceDigest:"0".repeat(64),
      statusSequence:1,validUntil:later(),statusObservedAt:now(),
      evaluatedAt:now(),organizationId:"org:one",workspaceId:workspace_id,
      grantId:"grant:publish",productionActivation:false,
      doesNotTransferData:true,doesNotAcceptCorporateCopy:true,
    }),
    verifyDecisionBinding:()=>true,
  };
  const kernel={
    sessionInfo:{contract_version:"1.3.0",runtime_version:"0.3.6"},
    hasOperation:()=>true,
    async getObject(ws,id){
      assert.equal(ws,workspace_id);
      const row=readers.get(id);
      return row?{object:structuredClone(row),
        relations:{outgoing:[],incoming:[]}}:null;
    },
    async listEventsSince(ws){
      assert.equal(ws,workspace_id);return structuredClone(events);
    },
    async listObjects({workspace_id:ws,schema_id}){
      assert.equal(ws,workspace_id);
      return [...readers.values()].filter(x=>x.schema_id===schema_id)
        .map(x=>structuredClone(x));
    },
    async putObject(input){
      assert.equal(input.workspace_id,workspace_id);
      assert.equal(input.base_revision,0);
      assert.equal(input.schema_id,ORIGINAL_AGENT_RESULT_SCHEMA);
      if(readers.has(input.object_id))throw Error("CAS original conflict");
      const record={...structuredClone(input),revision:1,deleted:false,
        deleted_at:null};
      const event={event_id:"event:kernel:1",
        workspace_id,event_type:ORIGINAL_AGENT_RESULT_EVENT,
        object_id:input.object_id,revision:1,
        payload:structuredClone(input.event.payload)};
      readers.set(input.object_id,record);events.push(event);writes.push(input);
      return {object:structuredClone(record),event:structuredClone(event),
        deduplicated:false};
    },
    async exportPreview({workspaces,include_history,include_assets,
      include_relations,include_schemas}){
      assert.deepEqual(workspaces,[workspace_id]);
      assert.equal(include_history,false);
      assert.equal(include_assets,false);
      assert.equal(include_relations,false);
      assert.equal(include_schemas,true);
      return {workspaces:[workspace_id],counts:{
        objects:readers.size,events:0,assets:0,relations:0}};
    },
    async exportPackage(options){
      assert.deepEqual(options.workspaces,[workspace_id]);
      assert.equal(readers.size,1);
      const bytes=Uint8Array.from(Buffer.from("genuine-t2-export-fixture-only"));
      const package_digest=hex(bytes);
      return {filename:"agent-result.iwxa",bytes,validation:{ok:true},package_digest,
        manifest:{workspaces:[workspace_id],
          workspace_states:[{workspace_id}],package_digest,
          counts:{objects:1,events:0,assets:0,relations:0}}};
    },
  };
  const source={
    currentOriginalContext:async()=>({contextDigest:binding.contextDigest}),
    async readAcceptedContent(input){
      assert.deepEqual(input,binding);
      return {status:acceptanceValid?"HUMAN_ACCEPTED_DRAFT":"DRAFT",
        readOnly:true,acceptedDigest:binding.acceptedDigest,
        taskId:binding.taskId,resultId:binding.resultId,
        workRef:binding.workRef,signedTaskId:binding.signedTaskId,
        signedTaskRevisionId:binding.signedTaskRevisionId,
        signedTaskPackageSha256:binding.signedTaskPackageSha256,
        resultText:text,resultTextSha256:hex(Buffer.from(text))};
    },
  };
  const originalExchange={
    async publishSignedFromOriginal(input){
      sends.push(input);
      assert.equal(input.operationId,operationId);
      assert.equal(input.recipientId,"iwxa.atlas");
      assert.equal(input.archiveSha256,hex(input.archiveBytes));
      receipts.set(input.operationId,{
        status:"VERIFIED",originalSignatureVerified:true,
        originalKernelReadbackVerified:true,operationId,
        recipientId:"iwxa.atlas",
        sourceObjectRef:structuredClone(input.sourceObjectRef),
        archiveSha256:input.archiveSha256,
        ...structuredClone(binding),
      });
      if(lostAck)throw Error("native original Exchange ACK lost");
    },
    async readVerifiedReceipt({operationId:id,recipientId,sourceObjectRef}){
      assert.equal(recipientId,"iwxa.atlas");
      assert.equal(sourceObjectRef.workspace_id,workspace_id);
      return structuredClone(receipts.get(id)??{
        status:"NOT_FOUND_CONFIRMED",operationId:id,
        recipientId,originalLedgerVerified:true});
    },
  };
  let approvals=0,grants=0;
  const opts={kernel,publicationWorkspaceId:workspace_id,
    accessForOperation:async()=>access,acceptedSource:source,originalExchange,
    authorizeRecipient:async request=>{
      grants++;
      return {allowed:!denyExport,rightClass:"DATA",
        action:"package.export",recipientId:"iwxa.atlas",
        operationId:request.operationId,workspaceId:workspace_id};},
    confirmHumanDisclosure:async()=>{approvals++;return true;},
    isHostActive:()=>true};
  const port=()=>createTrustedOriginalAgentResultPublication(opts);
  return {binding,operationId,port,workRef,writes,sends,source,events,
    reads:()=>readers.size,approvals:()=>approvals,grants:()=>grants};
}

test("original Agent publisher keeps T2 Kernel source and independently verified signed Exchange cold receipts",async()=>{
  const f=fixture(),first=f.port();
  assert.equal((await first.read_publication(f.operationId,f.binding)).status,"UNISSUED");
  const accepted=await first.publish_accepted({...f.binding,operationId:f.operationId});
  assert.equal(accepted.status,"COMMITTED");
  assert.equal(accepted.originalReceiptVerified,true);
  assert.equal(accepted.retrySafe,false);
  assert.equal(f.writes.length,1);
  assert.equal(f.sends.length,1);
  const original=await first.read_published(accepted.sourceObjectRef);
  assert.equal(original.acceptedDigest,f.binding.acceptedDigest);
  const lookedUp=await first.read_published_for(f.workRef,{
    taskId:f.binding.taskId,resultId:f.binding.resultId,
    acceptedDigest:f.binding.acceptedDigest,
    signedTaskId:f.binding.signedTaskId,
    signedTaskRevisionId:f.binding.signedTaskRevisionId,
    signedTaskPackageSha256:f.binding.signedTaskPackageSha256,
  },{taskId:f.binding.signedTaskId,
    taskRevisionId:f.binding.signedTaskRevisionId,
    packageSha256:f.binding.signedTaskPackageSha256});
  assert.deepEqual(lookedUp,original);
  const receipt=await first.read_receipt(accepted.sourceObjectRef,
    f.binding.taskId,f.binding.resultId,accepted.archiveSha256,"iwxa.atlas");
  assert.equal(receipt.originalSignatureVerified,true);
  assert.deepEqual(await first.read_latest_for_work("proj:real","work:203"),{
    status:"VERIFIED_ORIGINAL_WORK",revision:"3"});
  // Two independent cold Host adapters find the SAME genuine Kernel and
  // native owner receipts, without recreating the original Exchange archive.
  for(const cold of [f.port(),f.port()]){
    assert.equal((await cold.read_publication(f.operationId,f.binding))
      .status,"COMMITTED");
    assert.equal((await cold.publish_accepted({...f.binding,
      operationId:f.operationId})).status,"COMMITTED");
  }
  assert.equal(f.writes.length,1);
  assert.equal(f.sends.length,1);
});

test("lost signed Exchange ACK and unaccepted Agent drafts never trigger a second publication",async()=>{
  const f=fixture({lostAck:true}),port=f.port();
  const uncertain=await port.publish_accepted({...f.binding,
    operationId:f.operationId});
  assert.equal(uncertain.status,"OUTCOME_UNKNOWN");
  assert.equal(f.writes.length,1);
  assert.equal(f.sends.length,1);
  assert.equal((await port.read_publication(f.operationId,f.binding))
    .status,"COMMITTED");
  assert.equal((await f.port().publish_accepted({...f.binding,
    operationId:f.operationId})).status,"COMMITTED");
  assert.equal(f.sends.length,1);

  const invalid=fixture({acceptanceValid:false});
  await assert.rejects(invalid.port().publish_accepted({...invalid.binding,
    operationId:invalid.operationId}),{
    code:"T3_AGENT_ORIGINAL_ACCEPTED_RESULT_UNVERIFIED",
    outcome:"DENIED"});
  assert.equal(invalid.reads(),0);
  assert.equal(invalid.sends.length,0);
  const foreign=fixture({denyExport:true});
  await assert.rejects(foreign.port().publish_accepted({...foreign.binding,
    operationId:foreign.operationId}),{
    code:"T3_AGENT_ORIGINAL_ATLAS_EXPORT_NOT_AUTHORIZED",
    outcome:"DENIED"});
  assert.equal(foreign.reads(),0);
  assert.equal(foreign.sends.length,0);
});
