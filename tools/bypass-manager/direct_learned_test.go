func TestDirectLearnedPrivateHostlistSelection(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "direct-auto-hosts.txt")
	payload := "\n# generated by engine\nLOCALHOST\ninternal.example\nexample.org\nEXAMPLE.ORG\n!blocked.org\n^special.org\ncdn.site.ru\n192.168.1.1\nmetadata.google.internal\nuser:password@site.ru\n"
	if err := os.WriteFile(path, []byte(payload), 0600); err != nil { t.Fatal(err) }
	hosts, state := readDirectLearnedHosts(path)
	if state != "LEARNED_HOSTS_PRESENT" || len(hosts) != 2 || hosts[0] != "cdn.site.ru" || hosts[1] != "example.org" {
		t.Fatalf("hosts=%q state=%s", hosts, state)
	}
	seen := make(map[string]bool)
	calls := []string{}
	var callsMu sync.Mutex
	a := func(_ context.Context, h string) string {
		callsMu.Lock()
		calls = append(calls, h)
		callsMu.Unlock()
		if strings.HasPrefix(h, "cdn") { return "TLS_CONFIRMED" }
		return "TLS_FAILED"
	}
	r := probeNewDirectLearned(context.Background(), path, seen, a)
	if !validDirectLearned(r) || r.Learned != 2 || r.Probed != 2 || r.TLSConfirmed != 1 || r.TLSFailed != 1 {
		t.Fatalf("result=%+v", r)
	}
	r2 := probeNewDirectLearned(context.Background(), path, seen, a)
	if r2.State != "NO_NEW_HOSTS" || r2.Probed != 0 || len(calls) != 2 {
		t.Fatalf("repeat=%+v calls=%q", r2, calls)
	}
	if strings.Contains(r.Caveat, "site.ru") || strings.Contains(r.State, "example.org") { t.Fatal("private host exported") }
}

func TestDirectLearnedRejectsUnsafeNamesAndLargeFile(t *testing.T) {
	for _, host := range []string{"localhost", "a.local", "a.internal", "198.51.100.5", "[::1]", "-bad.org", "bad-.org", "*.bad.org", "user@site.org", "site.org/path", "org", "123.123", "site.onion", "site.test", "site.example", "UPPER.ORG", "a..org"} {
		if validDirectHost(host) { t.Errorf("accepted unsafe host %q", host) }
	}
	for _, host := range []string{"example.org", "site.ru", "cdn.example.net", "xn--bcher-kva.de"} {
		if !validDirectHost(host) { t.Errorf("rejected valid host %q", host) }
	}
	path := filepath.Join(t.TempDir(), "list.txt")
	os.WriteFile(path, []byte(strings.Repeat("a.example.org\n", 15000)), 0600)
	hosts, state := readDirectLearnedHosts(path)
	if len(hosts) != 0 || state != "LOCAL_LIST_TOO_LARGE" { t.Fatal(len(hosts), state) }
	os.Remove(path)
	hosts, state = readDirectLearnedHosts(path)
	if state != "NO_LEARNED_HOSTS" || len(hosts) != 0 { t.Fatal(state) }
}

func TestDirectLearnedRejectsInvalidExport(t *testing.T) {
	r := DirectLearnedReport{SchemaVersion: "1.0", CheckedUTC: utc(), State: "TLS_SAMPLED", Learned: 2, Probed: 1, TLSConfirmed: 1, Caveat: directLearnedCaveat}
	if !validDirectLearned(r) { t.Fatal("expected valid") }
	r.State = "private.example.org"
	if validDirectLearned(r) { t.Fatal("unsafe status accepted") }
	r.State = "TLS_SAMPLED"
	r.Probed = 3
	if validDirectLearned(r) { t.Fatal("overlimit probe accepted") }
}
